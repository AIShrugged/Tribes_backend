<?php

namespace App\Support;

/**
 * Normalize a person's name for fuzzy matching.
 *
 * Transliterates Cyrillic → Latin so "Слава" matches a user named "slava",
 * lowercases, trims and collapses inner whitespace.
 *
 * Used by name-matchers in {@see \App\Services\IssueMergeService::nameMatches}
 * and {@see \App\Services\Decisions\DecisionAuthorResolver::namesMatch}.
 */
final class NameNormalizer
{
    private const CYRILLIC_TO_LATIN = [
        'А' => 'A', 'Б' => 'B', 'В' => 'V', 'Г' => 'G', 'Д' => 'D', 'Е' => 'E', 'Ё' => 'E',
        'Ж' => 'Zh', 'З' => 'Z', 'И' => 'I', 'Й' => 'Y', 'К' => 'K', 'Л' => 'L', 'М' => 'M',
        'Н' => 'N', 'О' => 'O', 'П' => 'P', 'Р' => 'R', 'С' => 'S', 'Т' => 'T', 'У' => 'U',
        'Ф' => 'F', 'Х' => 'Kh', 'Ц' => 'Ts', 'Ч' => 'Ch', 'Ш' => 'Sh', 'Щ' => 'Sch',
        'Ъ' => '', 'Ы' => 'Y', 'Ь' => '', 'Э' => 'E', 'Ю' => 'Yu', 'Я' => 'Ya',

        'а' => 'a', 'б' => 'b', 'в' => 'v', 'г' => 'g', 'д' => 'd', 'е' => 'e', 'ё' => 'e',
        'ж' => 'zh', 'з' => 'z', 'и' => 'i', 'й' => 'y', 'к' => 'k', 'л' => 'l', 'м' => 'm',
        'н' => 'n', 'о' => 'o', 'п' => 'p', 'р' => 'r', 'с' => 's', 'т' => 't', 'у' => 'u',
        'ф' => 'f', 'х' => 'kh', 'ц' => 'ts', 'ч' => 'ch', 'ш' => 'sh', 'щ' => 'sch',
        'ъ' => '', 'ы' => 'y', 'ь' => '', 'э' => 'e', 'ю' => 'yu', 'я' => 'ya',
    ];

    public static function normalize(string $name): string
    {
        $latin = strtr($name, self::CYRILLIC_TO_LATIN);
        $lower = mb_strtolower(trim($latin));

        return preg_replace('/\s+/', ' ', $lower);
    }
}
