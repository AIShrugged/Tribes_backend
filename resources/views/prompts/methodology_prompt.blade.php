## Входные данные
1. Текст с методикой.
2. Файл с транскриптом одной встречи между менеджером по продажам и клиентом.
Формат транскрипта — список реплик с указанием имени говорящего и временной отметки.

### Пример входа:
```
0:02 - Ekaterina Gudozhnikova
Здравствуйте, коллеги! Хотела бы спросить, можем ли мы поставить встречную запись, потому что будем обсуждать детали.

0:40 - Влада
Екатерина, да? Здравствуйте. Смотрели предложение, у нас есть корректировки и вопросы для уточнения.
```

---

## Задача ИИ
1. На основе методики извлечь структуру оценки.
2. Проанализировать разговор по этапам продаж.
3. Рассчитать баллы по каждой метрике согласно методики.
4. Сформировать общее заключение по работе менеджера:
- Сильные стороны
- Зоны для развития
- План действий
5. Вернуть всё в виде JSON по указанной схеме.

## Выходной формат: JSON
Ожидаемый результат должен соответствовать следующей JSON-схеме:
{{$scheme}}

---

## Дополнительные требования
- Обязательно использовать **цитаты из транскрипта** для подтверждения выставленных оценок.
- Итоговый **total_score** = сумма всех метрик.

---

## Цель
Сформировать полноценную автоматизированную систему оценки эффективности работы менеджеров по продажам по методике.
